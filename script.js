const storedTheme = localStorage.getItem("portfolio-theme");
if (storedTheme === "light") body.classList.add("light");

function updateThemeIcon() {
  themeToggle.innerHTML = body.classList.contains("light")
    ? '<i class="fa-solid fa-moon"></i>'
    : '<i class="fa-solid fa-sun"></i>';
}
updateThemeIcon();

themeToggle.addEventListener("click", () => {
  body.classList.toggle("light");
  localStorage.setItem("portfolio-theme", body.classList.contains("light") ? "light" : "dark");
  updateThemeIcon();
});

const storedLang = localStorage.getItem("portfolio-language") || "en";
setLanguage(storedLang);

function setLanguage(lang) {
  const dict = translations[lang];
  html.lang = lang;
  html.dir = lang === "ar" ? "rtl" : "ltr";
  langToggle.querySelector(".lang-label").textContent = lang === "en" ? "AR" : "EN";

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (Object.prototype.hasOwnProperty.call(dict, key)) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (dict[key]) el.placeholder = dict[key];
  });

  localStorage.setItem("portfolio-language", lang);
}

langToggle.addEventListener("click", () => {
  setLanguage(html.lang === "en" ? "ar" : "en");
  closeMenu();
});

function openMenu() {
  mainNav.classList.add("open");
  menuToggle.classList.add("active");
  menuToggle.setAttribute("aria-expanded", "true");
  body.classList.add("menu-open");
}
function closeMenu() {
  mainNav.classList.remove("open");
  menuToggle.classList.remove("active");
  menuToggle.setAttribute("aria-expanded", "false");
  body.classList.remove("menu-open");
}
menuToggle.addEventListener("click", () => {
  mainNav.classList.contains("open") ? closeMenu() : openMenu();
});
mainNav.querySelectorAll("a").forEach(link => link.addEventListener("click", closeMenu));

window.addEventListener("scroll", () => {
  header.classList.toggle("scrolled", window.scrollY > 25);

  const sections = [...document.querySelectorAll("main section[id]")];
  const navLinks = [...mainNav.querySelectorAll("a")];
  let current = "home";

  sections.forEach(section => {
    if (window.scrollY >= section.offsetTop - 160) current = section.id;
  });

  navLinks.forEach(link => link.classList.toggle("active", link.getAttribute("href") === `#${current}`));
});

const revealObserver = new IntersectionObserver((entries, observer) => {
  entries.forEach(entry => {
    if (!entry.isIntersecting) return;
    entry.target.classList.add("visible");
    observer.unobserve(entry.target);
  });
}, { threshold: 0.12 });

document.querySelectorAll(".reveal").forEach(el => revealObserver.observe(el));

const skillObserver = new IntersectionObserver((entries, observer) => {
  entries.forEach(entry => {
    if (!entry.isIntersecting) return;
    entry.target.querySelectorAll(".skill-row").forEach(row => {
      const bar = row.querySelector(".skill-bar span");
      bar.style.width = `${row.dataset.level}%`;
    });
    observer.unobserve(entry.target);
  });
}, { threshold: 0.2 });
document.querySelectorAll(".skill-group").forEach(el => skillObserver.observe(el));

